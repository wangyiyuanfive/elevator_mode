"""
PLC通信配置文件
SIEMENS S7-1200 PLC连接参数和寄存器地址定义

"""

# ============================================================
# PLC连接参数
# 这里不管是1200、1500、300、400，只要配置了MB Server就可以
# ============================================================
PLC_IP = "192.168.6.180"    # PLC的IP地址
PLC_PORT = 502              # PLC modbus通讯参数的端口
UNIT_ID = 1                 # 从站ID（Slave ID）  -- 对于现在用modbus server，这个参数其实没用

# ============================================================
# 寄存器地址定义
# 西门子PLC的保持寄存器从40001开始
# Modbus协议地址 = 40001 - 40001 = 0
# ============================================================
HOLDING_REG_START = 0       # 起始地址
HOLDING_REG_COUNT = 20      # 默认读取数量

# ============================================================
# 超时设置
# ============================================================
CONNECTION_TIMEOUT = 5      # 连接超时 秒
REQUEST_TIMEOUT = 3         # 请求超时 秒


# ============================================================
# 数据采集配置
# 建议别小于100，越大越好（但是会丢失数据精度）
# 太小了对PLC有通讯压力，也有存储压力
# ============================================================
SAMPLE_INTERVAL_MS = 100    # 采集间隔（毫秒），范围: 10-10000


# ============================================================
# 数据类型配置
# 可选类型: "int16", "uint16", "int32", "uint32", "float32"
# Modbus是uint16，其他的都做了转换，但是从PLC读，其实也不一定需要吧，后续再处理，原生的最好
# ============================================================

# 寄存器地址与数据类型映射表
# 格式: {起始地址: (数据类型, "描述")}
REGISTER_TYPE_MAP = {
    0: ("uint16", "VALUE1"),
    1: ("uint16", "VALUE2"),
    2: ("uint16", "VALUE3"),
    3: ("uint16", "VALUE4"),
    4: ("uint16", "VALUE5"),
    5: ("uint16", "VALUE6"),
    6: ("uint16", "VALUE7"),
    7: ("uint16", "VALUE8"),
    8: ("uint16", "VALUE9"),
    9: ("uint16", "VALUE10"),
    10: ("uint16", "VALUE11"),
}


# ============================================================
# 数据类型说明
# ============================================================
# int16:   有符号16位整数, 范围 -32768 ~ 32767,      占用1个寄存器
# uint16:  无符号16位整数, 范围 0 ~ 65535,           占用1个寄存器
# int32:   有符号32位整数, 范围 -2147483648 ~ ... ,  占用2个寄存器
# uint32:  无符号32位整数, 范围 0 ~ 4294967295,      占用2个寄存器
# float32: 32位浮点数, IEEE 754标准,                占用2个寄存器